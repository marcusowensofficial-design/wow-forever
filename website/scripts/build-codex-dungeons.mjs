/**
 * Builds js/data/codex-dungeons-data.js: bosses and loot for the nine new dungeons, shown in the codex
 * pop-up. Levels 35-60 come from the dungeon guides' curated.mjs, levels 13-33 from ForeverDungeonJournal.
 * Item names, levels and stats always come from the item database, so an unknown item fails the build.
 *
 * Usage: node scripts/build-codex-dungeons.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';
import { GUIDES } from './forever-dungeon-guides/curated.mjs';
import { readLuaTable } from './forever-dungeon-guides/lua-table.mjs';
import { createItemInfo, journalSlots } from './lib/guide-items.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'js', 'data', 'codex-dungeons-data.js');
const lua = fs.readFileSync(path.join(ROOT, '..', 'addons', 'ForeverDungeonJournal', 'Data', 'Dungeons.lua'), 'utf8');
const ctx = { window: {} };
vm.createContext(ctx);
vm.runInContext(fs.readFileSync(path.join(ROOT, 'js', 'data', 'item-database-data.js'), 'utf8'), ctx);
const itemInfo = createItemInfo(ctx.window.WOW_ITEM_DATABASE, journalSlots(lua));

function drops(ids, where) {
  return [...new Set(ids)].map((id) => {
    const i = itemInfo(id);
    if (!i) throw new Error(`${where}: item ${id} is not in the item database`);
    return { id: i.id, name: i.name, quality: `q${i.q}`, iLvl: i.ilvl > 1 ? i.ilvl : 0, slot: i.kind, stats: i.stats.replace(/\+-/g, '-') };
  });
}

const out = {};
const CURATED = [['dungeon-05', 'the-drowned-city'], ['dungeon-06', 'kroldok-stronghold'], ['dungeon-07', 'alcaz-prison'], ['dungeon-08', 'blackmaw-hold'], ['dungeon-09', 'shapers-terrace']];
for (const [id, slug] of CURATED) {
  const g = GUIDES.find(x => x.slug === slug);
  const optional = (n) => /^Rares|^Kroog/.test(n);
  out[id] = {
    name: g.name, slug, guideId: g.id, levels: g.levels, zone: g.zone,
    entrance: `${g.coords}. ${g.access}`,
    source: 'Dungeon guide and item database, November 24, 2026',
    bosses: g.route.map(b => ({
      name: b.name.replace(/^\d+\. /, '').replace(/^Rares: /, 'Rare spawns: ').replace(/ \((final|last)\)/, ''),
      rare: optional(b.name), drops: drops(b.loot, `${slug} ${b.name}`)
    })),
    trash: drops(g.trashLoot, `${slug} trash`)
  };
}

const JOURNAL = [
  ['dungeon-01', 'hall-of-thanes', 'Hall of Thanes', [13, 18], 'guide-hall-of-thanes'],
  ['dungeon-02', 'ruins-of-lordaeron', 'Ruins of Lordaeron', [15, 20], 'guide-ruins-of-lordaeron'],
  ['dungeon-03', 'excavation-site', 'Excavation Site: Wetlands', [26, 31], 'guide-excavation-site'],
  ['dungeon-04', 'city-of-dalaran', 'City of Dalaran', [28, 33], 'guide-city-of-dalaran']
];
const main = readLuaTable(lua, 'FDJ.DB =');
for (const [id, slug, name, levels, guideId] of JOURNAL) {
  const db = main[name] || readLuaTable(lua, `FDJ.DB["${name}"] =`);
  const ids = (b) => (b.loot || []).map(l => (Array.isArray(l) ? l : l.list || [])[0]).filter(Number.isInteger);
  const isTrash = (b) => /^Trash/.test(b.name);
  out[id] = {
    name, slug, guideId, levels, zone: db.location,
    source: 'ForeverDungeonJournal and item database',
    bosses: db.bosses.filter(b => !isTrash(b)).map(b => ({ name: b.name, rare: false, drops: drops(ids(b), `${slug} ${b.name}`) })),
    trash: drops(db.bosses.filter(isTrash).flatMap(ids), `${slug} trash`)
  };
}

fs.writeFileSync(OUT, `/**
 * World of Warcraft: Forever - Boss and loot tables for the codex dungeon pop-up.
 * GENERATED by scripts/build-codex-dungeons.mjs. Do not edit by hand.
 */
window.WOW_CODEX_DUNGEONS = ${JSON.stringify(out, null, 1)};
`, 'utf8');
for (const [id, d] of Object.entries(out)) console.log(id, d.name, `${d.bosses.length} entries`, `${d.bosses.reduce((n, b) => n + b.drops.length, d.trash.length)} drops`);
