/**
 * Builds js/data/topic-guides-data.js: Sunken Temple class quests, the Dawn Waker secret, secret toys,
 * Craftsman's Writs, riding and first mounts, weapon skills, bags and storage, and the Shen'dralar.
 *
 * Text lives in curated.mjs. Item names and stats come from the item database, prices from the latest
 * Auction House scan, recipe costs from professions-data.js, writs from data/scraped/craftsman-writs.json.
 *
 * Usage: node scripts/topic-guides/build.mjs   (re-run after refreshing market-data.js)
 */
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';
import { cell, itemUrl, questUrl, createItemInfo, journalSlots, guideBundle } from '../lib/guide-items.mjs';
import { makeGuides } from './curated.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const OUT = path.join(ROOT, 'js', 'data', 'topic-guides-data.js');
const LUA = path.join(ROOT, '..', 'addons', 'ForeverDungeonJournal', 'Data', 'Dungeons.lua');
const CHECKED = 'November 24, 2026';

const ctx = { window: {} };
vm.createContext(ctx);
for (const f of ['item-database-data.js', 'market-data.js', 'professions-data.js', 'bis-60-data.js']) {
  vm.runInContext(fs.readFileSync(path.join(ROOT, 'js', 'data', f), 'utf8'), ctx);
}
const W = ctx.window;
const itemInfo = createItemInfo(W.WOW_ITEM_DATABASE, journalSlots(fs.readFileSync(LUA, 'utf8')));
const tooltips = {};
const MARKET = W.WOW_MARKET_SCAN_DATA;
const realm = MARKET.activeRealm.replace('_', ' ');
const scanDate = new Date(MARKET.lastScanTime * 1000).toLocaleDateString('en-US', { year: 'numeric', month: 'long', day: 'numeric', timeZone: 'UTC' });

/** Markdown link for an item; throws when the id is not in the item database. */
function item(id) {
  const i = itemInfo(id);
  if (!i) throw new Error(`item ${id} is not in the item database`);
  i.stats = i.stats.replace(/\+-/g, '-');
  tooltips[i.id] = i;
  return `[${cell(i.name)}](${itemUrl(i.id)})`;
}
const stats = (id) => itemInfo(id)?.stats.replace(/\+-/g, '-') || '';
const quest = (id, name) => `[${name}](${questUrl(id)})`;
const guide = (id, label) => `[${label}](#guides/${id})`;

/** Copper to "1g 20s". Null means no price in the scan. */
function money(copper) {
  if (copper == null) return '–';
  const g = Math.floor(copper / 10000), s = Math.floor((copper % 10000) / 100), c = Math.round(copper % 100);
  if (g) return `${g.toLocaleString('en-US')}g${s && g < 100 ? ` ${s}s` : ''}`;
  return s ? `${s}s` : `${c}c`;
}
/** 14-day median, or null. One scan's lowest buyout swings too much to rely on. */
const price = (id) => MARKET.prices[id]?.med14 || MARKET.prices[id]?.minBuyout || null;

const recipes = new Map();
for (const p of Object.values(W.WOW_PROFESSIONS_DATA)) {
  for (const r of p.recipes || []) if (!recipes.has(r.name.toLowerCase())) recipes.set(r.name.toLowerCase(), r);
}
const RECIPE_ALIASES = { "pearl-handled dagger": 'pearl-handled dagger', 'gyromatic micro-adjuster': 'gyromatic micro-adjustor' };

/** Cheapest way to get one crafted item: buy it, or buy every material. */
function cheapest(product) {
  const key = product.toLowerCase();
  const r = recipes.get(RECIPE_ALIASES[key] || key);
  const ah = MARKET.byName[key]?.med14 || null;
  if (!r) return { cost: ah, how: ah ? 'Buy' : null };
  const parts = r.reagents.map(x => (price(x.id) == null ? null : price(x.id) * x.count));
  const mats = parts.length && parts.every(x => x != null) ? parts.reduce((a, b) => a + b, 0) : null;
  if (ah == null && mats == null) return { cost: null, how: null };
  return mats != null && (ah == null || mats < ah) ? { cost: mats, how: 'Craft' } : { cost: ah, how: 'Buy' };
}

function bisSpecs(id) {
  const out = new Set();
  for (const c of W.WOW_BIS_DATA_60.classes) for (const sp of W.WOW_BIS_DATA_60[c.id].specs) {
    if (new RegExp(`"itemId":"?${id}"?[,}]`).test(JSON.stringify(sp))) out.add(`${sp.name} ${c.name}`);
  }
  return [...out];
}

const writs = JSON.parse(fs.readFileSync(path.join(ROOT, 'data', 'scraped', 'craftsman-writs.json'), 'utf8'));
const guides = makeGuides({ item, stats, quest, guide, money, price, cheapest, bisSpecs, writs, cell, realm, scanDate, CHECKED });

const header = [
  'World of Warcraft: Forever - Topic Guides (class quests, secrets, writs, riding, weapons, bags, Shen\'dralar)',
  `GENERATED by scripts/topic-guides/build.mjs. Text checked ${CHECKED}. Do not edit by hand:`,
  'change scripts/topic-guides/curated.mjs and re-run the build.'
];
fs.writeFileSync(OUT, guideBundle({ header, globalName: 'WOW_TOPIC_GUIDES', guides, tooltips }), 'utf8');
for (const g of guides) console.log(`${g.id.padEnd(36)} ${g.content.length} chars`);
