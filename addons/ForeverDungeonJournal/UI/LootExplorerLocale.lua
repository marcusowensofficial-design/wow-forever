local function Lookup(s)
    local lang = FDJ.GetLanguage and FDJ.GetLanguage() or "enUS"
    local t = FDJ.LOOT_EXPLORER_TEXT[lang]
    return t and t[s]
end

-- Translates a Loot Explorer label. Handles colour-wrapped text, "Req Lvl 20-30",
-- "Current: X" / "Viewed: X", "My Class (X)" and header sort arrows.
function FDJ.LootExplorerText(s)
    if type(s) ~= "string" or s == "" then return s end
    local lang = FDJ.GetLanguage and FDJ.GetLanguage() or "enUS"
    if lang == "enUS" or not FDJ.LOOT_EXPLORER_TEXT[lang] then return s end
    local hit = Lookup(s)
    if hit then return hit end
    -- colour-coded pieces: |cffxxxxxxText|r
    if s:find("|c", 1, true) then
        return (s:gsub("(|c%x%x%x%x%x%x%x%x)(.-)(|r)", function(c, inner, r)
            return c .. FDJ.LootExplorerText(inner) .. r
        end))
    end
    local lvl = s:match("^Req Lvl (.+)$")
    if lvl then return (Lookup("Req Lvl") or "Req Lvl") .. " " .. lvl end
    local key, rest = s:match("^(Current): (.+)$")
    if not key then key, rest = s:match("^(Viewed): (.+)$") end
    if key then return (Lookup(key) or key) .. ": " .. rest end
    local cls = s:match("^My Class %((.+)%)$")
    if cls then return (Lookup("My Class") or "My Class") .. " (" .. cls .. ")" end
    local base, arrow = s:match("^(.-)(%s+[\226][\150][\178\188])$")
    if base then return FDJ.LootExplorerText(base) .. arrow end
    local head, inner = s:match("^(.-) %((.+)%)$")
    if head then
        local word, arrow2 = inner:match("^(.-)(%s+[\226][\150][\178\188])$")
        word = word or inner
        return FDJ.LootExplorerText(head) .. " (" .. (Lookup(word) or word) .. (arrow2 or "") .. ")"
    end
    return s
end
